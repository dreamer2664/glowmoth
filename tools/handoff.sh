#!/usr/bin/env bash
# handoff.sh — THE RELAY: one command to be replaced without losing a byte.
# A dying (or aging) agent runs this; the successor reads RELAY.md and resumes.
#
# usage: ./handoff.sh <job-or-task-id> [reason]
#   reason: planned-rotation | aging | sandbox-crash-risk | lane-change | ordered
set -euo pipefail

ID="${1:?usage: handoff.sh <job-or-task-id> [reason]}"
REASON="${2:-planned-rotation}"
ME="${AGENCY_AGENT:?set AGENCY_AGENT first}"
REPO_DIR="$(git rev-parse --show-toplevel)"; cd "$REPO_DIR"
NOW="$(date -u +%FT%TZ)"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"
SHA="$(git rev-parse --short HEAD)"

JOB_DIR="jobs/$ID"
[ -d "$JOB_DIR" ] || mkdir -p "$JOB_DIR"
RELAY="$JOB_DIR/RELAY.md"

{
  echo "# RELAY — $ID"
  echo "<!-- generated by handoff.sh · $NOW · $ME · $REASON -->"
  echo "<!-- successor: read ONLY this file + HANDOFF.md. Resume in five minutes. -->"
  echo ""
  echo "## custody"
  echo "- from: $ME (age: $(python3 - <<EOF
import json,os
try:
    d=json.load(open('agents/$ME.json'))
    from datetime import datetime,timezone
    b=datetime.fromisoformat(d['joined_ts'].replace('Z','+00:00'))
    print(f"{(datetime.now(timezone.utc)-b).total_seconds()/3600:.1f}h since joined_ts")
except Exception as e: print('unknown')
EOF
))"
  echo "- reason: $REASON"
  echo "- branch: $BRANCH @ $SHA"
  echo "- handoff ts: $NOW"
  echo ""
  echo "## state of the work"
  if [ -f "$JOB_DIR/HANDOFF.md" ]; then
    tail -n 12 "$JOB_DIR/HANDOFF.md" | sed 's/^/  /'
  else
    echo "  (no HANDOFF.md — this job was never checkpointed. Re-derive from git log.)"
  fi
  echo ""
  echo "## my decision log (assumptions the successor must inherit)"
  if [ -f "$JOB_DIR/AMENDMENTS.md" ]; then cat "$JOB_DIR/AMENDMENTS.md"; else echo "_(none recorded — distrust the brief's clarity)_"; fi
  echo ""
  echo "## traps I found in THIS sandbox (free tuition — do not rediscover)"
  echo "- (agent fills this: tool bugs, OOM cliffs, install quirks, flaky gates)"
  echo ""
  echo "## next steps (unambiguous, in order)"
  echo "1. <first concrete action with file/branch/SHA>"
  echo "2. <second>"
  echo ""
  echo "## caps I had (manager: pick successor with these)"
  echo "- $(python3 -c "import json;print(json.load(open('agents/$ME.json')).get('caps','—'))" 2>/dev/null || echo —)"
} > "$RELAY"

# checkpoint the lease honestly, then release it
if command -v python3 >/dev/null && [ -f bin/agency ]; then
  python3 bin/agency tasks heartbeat "$ID" \
    --note "handoff: $ME → successor wanted ($REASON) @ $SHA; see $RELAY" >/dev/null 2>&1 || true
  python3 bin/agency tasks release "$ID" >/dev/null 2>&1 || true
  python3 bin/agency ping --topic jobs \
    "relay: $ME hands off $ID ($REASON) @ $SHA — successor claim and read $RELAY" >/dev/null 2>&1 || true
fi

# push the relay (append-only; the archive outlives the session)
git add "$RELAY" 2>/dev/null || true
if [ -f "$JOB_DIR/HANDOFF.md" ]; then git add "$JOB_DIR/HANDOFF.md" || true; fi
git commit -m "relay: $ID from $ME ($REASON)" >/dev/null 2>&1 || true
git push origin "$BRANCH" >/dev/null 2>&1 || git push -u origin "$BRANCH" >/dev/null 2>&1 || true

echo "RELAY WRITTEN: $RELAY (branch $BRANCH @ $SHA)"
echo "Successor protocol: claim the job → read RELAY.md + HANDOFF.md → continue on same branch → replace 'traps' with yours."
